export const VIETNAMESE_BIG_WISHES = (name: string, relationship: string, interests: string[] = []) => {
    const wishes = [
        { emoji: "🎯", wish: `Chúc ${name} đạt nguyện vọng 1 và bước vào cánh cổng đại học mơ ước!` },
        { emoji: "💎", wish: `${name} là những viên ngọc quý của lớp mình. Hãy luôn tỏa sáng nhé.` }
    ];
    if (relationship === 'partner') {
        wishes.push(
            { emoji: "❤️", wish: `Mỗi nhịp tim của mình đều là một lời chúc hạnh phúc dành cho ${name}.` },
            { emoji: "💍", wish: `Mong hành trình yêu thương của chúng ta sẽ luôn đẹp như vậy.` }
        );
    } else if (relationship === 'friend') {
        wishes.push(
            { emoji: "🌸", wish: `Chúc ${name} luôn xinh đẹp, vui vẻ và giữ mãi nụ cười rạng rỡ!` },
            { emoji: "📚", wish: `Chúc các bạn học thật tốt, thi thật giỏi và năm cuối cấp thật trọn vẹn.` }
        );
    }
    if (interests.some(i => i.toLowerCase().includes('car'))) {
        wishes.push({ emoji: "🏎️", wish: `Chúc cuộc sống của bạn tăng tốc trên con đường hạnh phúc!` });
    }
    if (interests.some(i => i.toLowerCase().includes('coding'))) {
        wishes.push({ emoji: "💻", wish: `Chúc năm mới của ${name} không có lỗi và đầy niềm vui!` });
    }
    return wishes;
};

